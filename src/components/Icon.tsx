export type IconName = keyof typeof PATHS;

export interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
}

export const Icon = ({ name, size = 20, color = "currentColor" }: IconProps) => {
  /* A few glyphs are two subpaths joined by "z"; split them back out so
     each renders as its own <path> with the right closure. */
  const raw = PATHS[name] ?? "";
  const segments = raw.split("z");

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {segments.map((segment, i) => {
        const d = segment.trim();
        if (!d) return null;
        /* Every segment except the last one had a "z" taken off it by the
           split, so it gets one back. The last did not. */
        const needsClose = i < segments.length - 1;
        return <path key={i} d={d + (needsClose ? "z" : "")} />;
      })}
    </svg>
  );
};
